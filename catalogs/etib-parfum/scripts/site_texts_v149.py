def direction(d):
    ns = all_notes(d); out = []
    for f in d.get('families', []):
        a = ADJ.get(f.split('|')[-1])
        if a and a not in out and NEEDS.get(a, lambda _: True)(ns): out.append(a)
    for test, a in NOTE_ADJ:
        if len(out) >= 3: break
        if a not in out and any(test(n) for n in ns): out.append(a)
    if d['type'] == 'Свежий': out = [a for a in out if a not in ('сладкое', 'гурманское', 'ванильное')]
    if d['type'] == 'Сладкий': out = [a for a in out if a != 'свежее']
    if not out: out = ['свежее' if d['type'] == 'Свежий' else 'сладкое']
    if d['type'] == 'Свежий' and out[0] not in ('свежее', 'цитрусовое', 'морское', 'зелёное', 'фужерное', 'цветочное', 'древесное'):
        out.insert(0, 'свежее')
    return ' · '.join(out[:3])


# ---- Кому подойдёт
def season(d):
    ns = all_notes(d); hv = heavy_count(d)
    if d['type'] == 'Свежий': return 'круглый год' if hv >= 2 else 'весна, лето'
    if d['type'] == 'Сладкий':
        return 'весна, лето, тёплые вечера' if any(any(s in n for s in SUNNY) for n in ns) else 'осень, зима, прохладные вечера'
    return 'осень, зима, прохладные вечера' if hv >= 3 else 'круглый год'


def occasion(d):
    fam = ' '.join(d.get('families', [])); hv = heavy_count(d)
    if 'sport' in d['name'].lower(): return 'повседневный, спорт, отдых'
    if d['type'] == 'Сладкий' or 'На вечер' in fam or 'Восточные выраженные' in fam: return 'свидание, вечерний выход, праздник'
    if d['type'] == 'Свежий': return 'офис, деловой выход, вечер' if hv >= 2 else 'повседневный, офис, отдых'
    return 'повседневный, офис, свидание'


def plural_adj(a):
    if a.endswith('ее'): return a[:-2] + 'ие'
    if a.endswith('ое'): return a[:-2] + ('ие' if a[-3] in 'кгхжшчщ' else 'ые')
    return a


def key_notes(d, k=2):
    p = notes_of(d); pool = p.get('heart', []) + p.get('base', []) + p.get('top', []) + p.get('all', [])
    seen, out = set(), []
    for n in sorted(pool, key=lambda n: -SCORE.get(theme(n) or '', 0)):
        t = theme(n) or n
        if t in seen: continue
        seen.add(t); out.append(n)
        if len(out) == k: break
    return out


def style(d):
    dirs = [plural_adj(a) for a in direction(d).split(' · ')][:2]
    kn = key_notes(d)
    tail = f'; главные ноты — {kn[0]} и {kn[1]}' if len(kn) == 2 else (f'; главная нота — {kn[0]}' if kn else '')
    verb = pick(d['number'] + d['category'], ['любит', 'ценит', 'выбирает'], 1)
    return f"для тех, кто {verb} {' и '.join(dirs)} ароматы{tail}"


# ---- Как звучит
def sound(d):
    p = notes_of(d); seed = d['number'] + d['category']
    if 'all' in p:
        xs = p['all']
        txt = f'Аромат построен на одной ноте — {xs[0]}.' if len(xs) == 1 else f'Аромат строится вокруг нот: {lst(xs)}.'
    else:
        v = lambda xs, s, pl: pl if (len(xs) > 1 or plural(xs[0])) else s
        parts = []
        if p.get('top'): parts.append(f"В начале {v(p['top'], 'звучит', 'звучат')} {lst(p['top'])}.")
        if p.get('heart'): parts.append(f"Затем {v(p['heart'], 'раскрывается', 'раскрываются')} {lst(p['heart'])}.")
        if p.get('base'): parts.append(f"В шлейфе {v(p['base'], 'остаётся', 'остаются')} {lst(p['base'])}.")
        txt = ' '.join(parts)
    hv = heavy_count(d)
    if d['type'] == 'Свежий':
        tail = 'Свежий старт уходит в глубокий тёплый шлейф.' if hv >= 2 else pick(seed, ['Звучит легко, чисто и прозрачно.', 'Звучание светлое и бодрое, без тяжести.', 'Прозрачный, чистый, с приятной свежестью.'], 2)
    elif d['type'] == 'Сладкий':
        tail = pick(seed, ['Звучит тепло, мягко и обволакивающе.', 'Тёплый и уютный, с долгим шлейфом.', 'Сладость тёплая и глубокая, без приторности.'], 2)
    else:
        tail = pick(seed, ['Свежесть сверху и мягкая сладость в шлейфе.', 'Свежее начало плавно переходит в тёплую мягкую базу.'], 2)
    return txt + ' ' + tail


