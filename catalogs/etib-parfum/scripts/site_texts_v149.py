SUNNY = ('кокос', 'тиаре', 'франжипани', 'монои', 'соль', 'песок')
SING = {'личи', 'киви', 'пачули', 'иланг-иланг', 'гедион'}


def notes_of(d):
    p = {k: [n.strip() for n in v.split(',') if n.strip()] for k, v in (d.get('pyr') or [])}
    return p or {'all': [n.strip() for n in d['composition'].split(',') if n.strip()]}


def all_notes(d):
    return [n.lower() for v in notes_of(d).values() for n in v]


def is_heavy(n):
    n = n.lower()
    return any(n == h or n.startswith(h + ' ') or n.endswith(' ' + h) for h in HEAVY) or 'ванил' in n or n.startswith('уд ')


def heavy_count(d):
    p = notes_of(d); return sum(is_heavy(n) for n in p.get('base', p.get('all', [])))


def pick(seed, xs, slot=0):
    return xs[(zlib.crc32(f'{seed}|{slot}'.encode()) >> 3) % len(xs)]


def plural(n):
    w = n.lower().split()[0]
    return w not in SING and w[-1] in 'ыи'


def lst(xs):
    xs = list(xs)
    if len(xs) > 3:
        keep = xs[:2]; extra = next((x for x in xs[2:] if is_heavy(x) or SCORE.get(theme(x) or '', 0) >= 5), xs[2])
        xs = keep + [extra]
    return xs[0] if len(xs) == 1 else ', '.join(xs[:-1]) + ' и ' + xs[-1]


