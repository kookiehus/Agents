def marketing(d, sex):
    p = notes_of(d); seed = d['number'] + d['category']; first = direction(d).split(' · ')[0]
    o = pick(seed, OPEN.get(first, ['Аромат с характером']), 3)
    if 'all' in p:
        s1 = f"{o}: {lst(p['all'])}."
    else:
        t, h, b = (lst(p.get(x) or ['—']) for x in ('top', 'heart', 'base'))
        s1 = pick(seed, SHAPE, 4).format(o=o, t=t, h=h, b=b)
    s2 = pick(seed, CHAR[d['type']], 5)
    who = {'женский': 'Для женщин, которые', 'мужской': 'Для мужчин, которые'}.get(sex, 'Подойдёт и мужчинам, и женщинам, которые')
    pref = 'любят тёплые глубокие ароматы' if (d['type'] == 'Сладкий' and sex == 'мужской') else WHO_PREF[d['type']]
    s3 = f"{who} {pref}."
    if d['category'] == 'ПРЕМИУМ' and pick(seed, [0, 1], 6): s3 += ' Селективный аромат для тех, кто ценит редкие композиции.'
    s4 = pick(seed, ['Идеален {w} {o}.', 'Лучше всего звучит {w} — {o}.', 'Носите его {w} {o}.'], 7).format(w=WHEN[season(d)], o=OCC[occasion(d)])
    return ' '.join([s1, s2, s3, s4]).replace(' с шлейф', ' со шлейф')


def colour(d):
    a = direction(d).split(' · ')[0]
    for c, ws in (('brown', ('восточное', 'древесное', 'табачное', 'кожаное', 'амбровое', 'пряное', 'алкогольное', 'кофейное', 'смолистое', 'терпкое')),
                  ('pink', ('цветочное', 'ягодное', 'фруктовое', 'сладкое', 'пудровое', 'гурманское', 'ванильное')),
                  ('green', ('свежее', 'зелёное', 'морское', 'фужерное', 'шипровое')), ('yellow', ('цитрусовое',))):
        if a in ws: return c
    return 'mauve'


